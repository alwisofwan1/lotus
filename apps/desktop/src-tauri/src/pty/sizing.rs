use super::*;

/// The desktop's own layout. Under a phone's lease it is remembered and applied when the
/// lease ends (`size_lease.rs`).
pub fn resize_session(
    session_id: String,
    cols: u16,
    rows: u16,
    state: &PtyState,
) -> Result<(), AppError> {
    let mut store = state.lock().map_err(|_| other("lock poisoned"))?;
    let session = store
        .0
        .get_mut(&session_id)
        .ok_or_else(|| other("session not found"))?;
    match session.sizing.desktop_resized((cols, rows)) {
        Some(size) => apply_size(session, size),
        None => Ok(()),
    }
}

pub(super) fn apply_size(session: &mut PtySession, (cols, rows): size_lease::Size) -> Result<(), AppError> {
    session.pty.resize(cols, rows).map_err(|e| other(e.to_string()))
}

/// What a phone's hold on a pane's size came to — the wire shape of `size_lease::Hold`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RemoteHold {
    Held { token: u64 },
    Lost,
}

/// Tokens only have to differ from each other within one run of the app.
pub(super) static NEXT_SIZE_TOKEN: AtomicU64 = AtomicU64::new(1);

/// A phone asks to draw this pane at its own size — a new hold with no token, a renewal with
/// one. See `size_lease.rs` for the rule.
pub fn hold_remote_size(
    session_id: &str,
    cols: u16,
    rows: u16,
    token: Option<u64>,
    state: &PtyState,
) -> Result<RemoteHold, AppError> {
    let mut store = state.lock().map_err(|_| other("lock poisoned"))?;
    let session = store
        .0
        .get_mut(session_id)
        .ok_or_else(|| other("session not found"))?;
    let current = session
        .pty
        .size()
        .map(|s| (s.cols, s.rows))
        .map_err(|e| other(e.to_string()))?;
    let fresh = NEXT_SIZE_TOKEN.fetch_add(1, Ordering::Relaxed);
    match session.sizing.hold(token, (cols, rows), current, std::time::Instant::now(), fresh) {
        size_lease::Hold::Held { token, apply } => {
            if let Some(size) = apply {
                apply_size(session, size)?;
            }
            Ok(RemoteHold::Held { token })
        }
        size_lease::Hold::Lost => Ok(RemoteHold::Lost),
    }
}

/// The phone left Terminal: the desktop's size goes back.
pub fn release_remote_size(session_id: &str, token: u64, state: &PtyState) -> Result<(), AppError> {
    let mut store = state.lock().map_err(|_| other("lock poisoned"))?;
    let Some(session) = store.0.get_mut(session_id) else {
        // Gone already; there is nothing left to give back.
        return Ok(());
    };
    match session.sizing.release(token) {
        Some(size) => apply_size(session, size),
        None => Ok(()),
    }
}

/// Bytes the desktop terminal wrote to this pane. A person at the desk takes the size back;
/// a report the terminal generated by itself does not (`size_lease::is_terminal_report`).
pub fn note_desktop_input(session_id: &str, data: &str, state: &PtyState) {
    if size_lease::is_terminal_report(data) {
        return;
    }
    let Ok(mut store) = state.lock() else { return };
    let Some(session) = store.0.get_mut(session_id) else { return };
    if let Some(size) = session.sizing.reclaim() {
        if let Err(err) = apply_size(session, size) {
            eprintln!("[pty] could not give {session_id} its desktop size back: {err}");
        }
    }
}

/// Ends every phone hold that went quiet past its lease. Run on a timer.
pub fn expire_remote_sizes(state: &PtyState) {
    let now = std::time::Instant::now();
    let Ok(mut store) = state.lock() else { return };
    for (id, session) in store.0.iter_mut() {
        if let Some(size) = session.sizing.expire(now) {
            if let Err(err) = apply_size(session, size) {
                eprintln!("[pty] could not give {id} its desktop size back: {err}");
            }
        }
    }
}
